"""Refresh the dashboard's data.

1. (optional) copy fresh analysis output into data/:
       python scripts/update_data.py --from path/to/out/ds
   analyze.py writes out/ds/<name>.json as {"rows": [...], "meta": [...]}; only the rows are kept.
2. Always: pack data/*.json into js/data-bundle.js, which the page loads.
   Bundling lets the page work inside sandboxed iframes, such as the ArcGIS Experience Builder
   Embed widget, without fetching files.

   python scripts/update_data.py            # just re-bundle data/
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FROM_ANALYSIS = ["counties", "designations", "disasters", "hazards", "emNotCarried"]
ALL = FROM_ANALYSIS + ["tnCounties"]  # tnCounties = county outlines (GeoJSON), not produced by analyze.py

ap = argparse.ArgumentParser()
ap.add_argument("--from", dest="src", help="folder with analyze.py's ds/*.json output")
args = ap.parse_args()

if args.src:
    for n in FROM_ANALYSIS:
        rows = json.loads((Path(args.src) / f"{n}.json").read_text())["rows"]
        (ROOT / "data" / f"{n}.json").write_text(json.dumps(rows, separators=(",", ":")))
        print(f"data/{n}.json  {len(rows)} rows")

bundle = {n: json.loads((ROOT / "data" / f"{n}.json").read_text()) for n in ALL}
(ROOT / "js" / "data-bundle.js").write_text(
    "// Generated by scripts/update_data.py from data/*.json. Do not edit by hand.\n"
    "window.DASH_DATA = " + json.dumps(bundle, separators=(",", ":")) + ";\n")
print("js/data-bundle.js written")
